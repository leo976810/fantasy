// Applies the daily hand-written judgment to data.json, so the daily Claude pass only has to write a
// few hundred characters of JSON instead of editing data.json by hand.
//   node apply-hand.mjs hand.json
// hand.json shape (every key optional except date):
//   { "date": "YYYY-MM-DD",                       // Taipei date the judgment was written
//     "todo": [{ "lv": "先做|建議|留意", "t": "標題", "d": "理由" }],
//     "threads": { "note": "...", "accounts": [{ "handle", "label", "post": "/@x/post/ID", "age": "11/12", "time": "ISO datetime", "sum" }],
//                  accounts are re-sorted newest first by time; give every post its time.
//                  "search": [], "skipped": "..." } }
// It sets handAsof.<key> to date for each key given and asof to now (Taipei). Everything else on the
// site is generated by update.mjs / build.mjs; pushing data.json triggers that pipeline.
import fs from 'node:fs';

const src = process.argv[2] || 'hand.json';
const H = JSON.parse(fs.readFileSync(src, 'utf8'));
const fail = m => { console.error('hand.json: ' + m); process.exit(1); };
if (!/^\d{4}-\d{2}-\d{2}$/.test(H.date || '')) fail('date must be YYYY-MM-DD');

const D = JSON.parse(fs.readFileSync('data.json', 'utf8'));
D.handAsof = D.handAsof || {};
const done = [];
if (H.todo) {
  if (!Array.isArray(H.todo) || !H.todo.every(x => ['先做', '建議', '留意'].includes(x.lv) && x.t && x.d)) fail('todo items need lv (先做/建議/留意), t, d');
  D.todo = H.todo; D.handAsof.todo = H.date; done.push('todo ' + H.todo.length);
}
if (H.threads) {
  const T = H.threads;
  if (!Array.isArray(T.accounts) || !T.accounts.every(a => a.handle && /^\/@[^/]+\/post\/[\w-]+$/.test(a.post || '') && a.sum)) fail('threads.accounts need handle, post (/@x/post/ID), sum');
  // Newest first across all accounts (by `time`, ISO from the post's <time datetime>). A post the
  // same account made within 1 min of its previous one is a continuation: it keeps that thread's
  // start time and follows it, so 續篇 never lands above its main post.
  const ms = a => Date.parse(a.time || '') || 0;
  const acc = T.accounts.map((a, i) => ({ handle: a.handle, label: a.label || a.handle, post: a.post, age: a.age || '', time: a.time || '', sum: a.sum, i }));
  const byTime = [...acc].sort((a, b) => ms(a) - ms(b) || a.i - b.i);
  const last = {};
  for (const a of byTime) { const p = last[a.handle]; a.k = p && ms(a) && ms(a) - ms(p) <= 60000 ? p.k : ms(a); last[a.handle] = a; }
  acc.sort((a, b) => b.k - a.k || ms(a) - ms(b) || a.i - b.i);
  D.threads = { note: T.note || '', accounts: acc.map(({ i, k, ...a }) => a), search: T.search || [], skipped: T.skipped || '' };
  D.handAsof.threads = H.date; done.push('threads ' + T.accounts.length);
}
if (!done.length) fail('nothing to apply (give todo and/or threads)');
D.asof = new Date().toLocaleString('sv-SE', { timeZone: 'Asia/Taipei' }).slice(0, 16) + '(台北時間)';
fs.writeFileSync('data.json', JSON.stringify(D, null, 1));
console.log('applied', done.join(', '), 'asof', D.asof);
